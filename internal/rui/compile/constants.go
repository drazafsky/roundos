package compile

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"go/token"
	"roundos/sdk/rui/bundle"
	"sort"
	"strings"
	"unicode"
)

// GoConstants returns gofmt'd, reproducible constants that app code can use to
// register its bindings/actions without manually retyping string identifiers.
func GoConstants(f *bundle.File, packageName string) ([]byte, error) {
	if packageName == "" {
		packageName = "main"
	}
	for i, r := range packageName {
		if !(r == '_' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))) {
			return nil, fmt.Errorf("invalid Go package name %q", packageName)
		}
	}
	if token.Lookup(packageName).IsKeyword() {
		return nil, fmt.Errorf("Go package name %q is a keyword", packageName)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by roundui; DO NOT EDIT.\npackage %s\n\n", packageName)
	fmt.Fprintf(&b, "const RUIApplicationID = %q\nconst RUIRootScreen = %q\n\n", f.Document.Application.ID, f.Document.Screens[0].ID)
	emit := func(prefix string, names []string) {
		for _, s := range names {
			// SHA suffix avoids collisions such as foo-bar and foo_bar.
			ident := strings.Builder{}
			ident.WriteString(prefix)
			for _, chunk := range strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
				if chunk == "" {
					continue
				}
				rs := []rune(chunk)
				ident.WriteString(strings.ToUpper(string(rs[0])))
				ident.WriteString(string(rs[1:]))
			}
			sum := sha256.Sum256([]byte(s))
			fmt.Fprintf(&b, "const %s_%x = %q\n", ident.String(), sum[:4], s)
		}
		b.WriteString("\n")
	}
	screens := make([]string, 0, len(f.Document.Screens))
	for _, s := range f.Document.Screens {
		screens = append(screens, s.ID)
	}
	sort.Strings(screens)
	emit("RUIScreen", screens)
	bindings := make([]string, 0, len(f.Manifest.Bindings))
	for k := range f.Manifest.Bindings {
		bindings = append(bindings, k)
	}
	sort.Strings(bindings)
	emit("RUIBinding", bindings)
	actions := make([]string, 0, len(f.Manifest.Actions))
	for _, a := range f.Manifest.Actions {
		actions = append(actions, a.Name)
	}
	emit("RUIAction", actions)
	return format.Source([]byte(b.String()))
}
